// Compiles contracts/*.sol with solc and writes lib/monad/artifacts.json (ABI + bytecode).
// Run: npm run contracts:compile
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import solc from "solc";

const dir = "contracts";
const sources = Object.fromEntries(
  readdirSync(dir)
    .filter((f) => f.endsWith(".sol"))
    .map((f) => [f, { content: readFileSync(join(dir, f), "utf8") }]),
);

const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    // "paris" bytecode runs on Monad (which supports everything through Osaka) and on local test chains.
    evmVersion: "paris",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors || []).filter((e) => e.severity === "error");
for (const e of out.errors || []) console[e.severity === "error" ? "error" : "warn"](e.formattedMessage);
if (errors.length) process.exit(1);

const artifacts = {};
for (const [file, contracts] of Object.entries(out.contracts)) {
  for (const [name, c] of Object.entries(contracts)) {
    if (!c.evm.bytecode.object) continue; // interfaces
    artifacts[name] = { source: file, abi: c.abi, bytecode: `0x${c.evm.bytecode.object}` };
  }
}
mkdirSync("lib/monad", { recursive: true });
writeFileSync("lib/monad/artifacts.json", JSON.stringify({ compiler: solc.version(), contracts: artifacts }, null, 2));
// Typed ABIs for the app (no bytecode, so the browser bundle stays small).
const abiTs = [
  "// Generated by scripts/compile.mjs. Do not edit by hand.",
  ...Object.entries(artifacts).map(([n, c]) => `export const ${n[0].toLowerCase() + n.slice(1)}Abi = ${JSON.stringify(c.abi, null, 2)} as const;\n`),
].join("\n");
writeFileSync("lib/monad/abi.ts", abiTs);
console.log(`Compiled ${Object.keys(artifacts).join(", ")} with solc ${solc.version()}`);
